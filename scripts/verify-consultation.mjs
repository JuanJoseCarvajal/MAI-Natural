import { createRequire } from "node:module";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.MAI_PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const base = "http://127.0.0.1:3000";
try {
  assert.equal((await page.goto(`${base}/services`)).status(), 200);
  await page.getByRole("heading", { name: /¿Y si esta vez/ }).waitFor();
  await page.screenshot({ path: "/tmp/mai-consultation-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Continuar", exact: true }).click();
  await page.locator("dialog[open]").waitFor();
  await page.locator("dialog[open]").getByRole("button", { name: "Continuar" }).click();
  await page.locator("dialog[open]").getByRole("alert").waitFor();
  await page.getByRole("radio", { name: /Mi piel y cómo la cuido/ }).check();
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("dialog[open]").count(), 0);
  await page.getByRole("button", { name: "Retomar mi encuentro" }).click();
  assert.equal(await page.getByRole("radio", { name: /Mi piel y cómo la cuido/ }).isChecked(), true);
  await page.screenshot({ path: "/tmp/mai-consultation-modal.png" });
  await page.getByRole("button", { name: "Continuar" }).click();
  await page.getByText("Podemos empezar por tu piel", { exact: false }).waitFor();
  await page.getByRole("radio", { name: /Salir con una orientación concreta/ }).check();
  await page.getByRole("button", { name: "Continuar" }).click();
  const future = new Date(Date.now() + 60 * 86400000).toISOString().slice(0, 10);
  await page.getByLabel("¿Qué día te gustaría?").fill(future);
  await page.getByRole("radio", { name: "09:00", exact: true }).check();
  await page.getByRole("button", { name: "Continuar" }).click();
  await page.getByRole("button", { name: "Revisar mi encuentro" }).click();
  await page.getByText("Correo inválido", { exact: true }).waitFor();
  await page.getByLabel("¿Cómo te llamas?").fill("Prueba local MAI");
  await page.getByLabel("Tu correo electrónico").fill("consulta-test@example.com");
  await page.getByLabel("Tu teléfono de contacto").fill("+573001234567");
  await page.getByRole("button", { name: "Revisar mi encuentro" }).click();
  await page.getByRole("button", { name: "Cambiar mis datos" }).click();
  assert.equal(await page.getByLabel("Tu correo electrónico").inputValue(), "consulta-test@example.com");
  await page.getByRole("button", { name: "Revisar mi encuentro" }).click();
  await page.getByRole("button", { name: "Solicitar mi encuentro" }).click();
  await page.locator("dialog[open]").getByRole("alert").waitFor();
  await page.getByRole("checkbox", { name: /Autorizo a MAI/ }).check();
  assert.equal(await page.getByRole("checkbox", { name: /Me gustaría conocer el Círculo/ }).isChecked(), false);
  await page.getByRole("button", { name: "Solicitar mi encuentro" }).click();
  await page.getByText("Pendiente de confirmación y pago", { exact: true }).waitFor();
  assert.equal(await page.locator("dialog[open]").count(), 0);
  await page.getByRole("status").getByText("Tu solicitud fue recibida", { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.body.style.overflow), "");
  await page.screenshot({ path: "/tmp/mai-consultation-complete.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.reload();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole("button", { name: "Continuar", exact: true }).click();
  await page.screenshot({ path: "/tmp/mai-consultation-mobile.png" });
  await page.getByRole("radio", { name: /Todavía no sé cómo nombrarlo/ }).focus();
  await page.keyboard.press("Space");
  await page.getByRole("button", { name: "Continuar" }).click();
  await page.getByText("No necesitas llegar con una respuesta.", { exact: false }).waitFor();
  assert.equal(await page.getByRole("heading", { name: "¿Qué te gustaría llevarte?" }).evaluate(el => document.activeElement === el), true);
  assert.deepEqual(errors, []);
  console.log("PASS desktop/mobile, validation, contextual responses, preserved answers, consent, local request, keyboard/focus, no overflow or browser errors.");
} catch (error) { console.log(await page.locator("dialog").innerText()); await page.screenshot({ path: "/tmp/mai-modal-failure.png" }); throw error; } finally { await browser.close(); }
